/**
 * Refresh the bundled disposable-email domain list used to block throwaway
 * sign-ups (src/modules/auth/email-policy.ts).
 *
 * Source: github.com/disposable-email-domains/disposable-email-domains (CC0).
 *
 * Usage:
 *   npx tsx scripts/update-disposable-domains.ts
 *
 * Rewrites src/modules/auth/data/disposable-domains.ts — review the diff before committing.
 */
import { writeFileSync } from "fs";
import { join } from "path";
import { MAINSTREAM_EMAIL_DOMAINS } from "../src/modules/auth/email-policy";

const SOURCE_URL =
  "https://raw.githubusercontent.com/disposable-email-domains/disposable-email-domains/main/disposable_email_blocklist.conf";
const OUT_FILE = join(__dirname, "..", "src", "modules", "auth", "data", "disposable-domains.ts");
const DOMAIN_RE = /^[a-z0-9-]+(\.[a-z0-9-]+)+$/;

async function main(): Promise<void> {
  const response = await fetch(SOURCE_URL);
  if (!response.ok) throw new Error(`Fetch failed: HTTP ${response.status}`);
  const text = await response.text();

  const domains = [
    ...new Set(
      text
        .split("\n")
        .map((line) => line.trim().toLowerCase())
        .filter((line) => line && !line.startsWith("#") && DOMAIN_RE.test(line) && !MAINSTREAM_EMAIL_DOMAINS.has(line))
    ),
  ].sort();
  if (domains.length < 1000) throw new Error(`Only ${domains.length} domains — refusing to write a truncated list.`);

  const fetchedOn = new Date().toISOString().slice(0, 10);
  writeFileSync(
    OUT_FILE,
    `// Generated by scripts/update-disposable-domains.ts on ${fetchedOn} — do not edit by hand.\n` +
      `// Source: github.com/disposable-email-domains/disposable-email-domains (CC0), ${domains.length} domains.\n` +
      `export const DISPOSABLE_DOMAINS_UPDATED_ON = "${fetchedOn}";\n` +
      `export const DISPOSABLE_DOMAINS = \`\n${domains.join("\n")}\n\`;\n`
  );
  process.stdout.write(`Wrote ${domains.length} domains to ${OUT_FILE}\n`);
}

main().catch((error: unknown) => {
  console.error(error);
  process.exit(1);
});
